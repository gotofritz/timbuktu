// fixtureCorpusDir is the corpus the frozen vectors were recorded over. It
// lives next to the recorder in internal/eval, which is the package that
// writes it; this is the package that has the database wiring to score it.
var fixtureCorpusDir = filepath.Join("..", "eval", "testdata", "corpus")

// baselineFile is the metrics the committed fixture produces, regenerated by
// `make eval-record` alongside the vectors so that switching embedder never
// means hand-editing a number in a test.
const baselineFile = "baseline.json"

// Baseline is what the fixture corpus scored when it was last recorded. The
// instrument is recorded with it: two sets of numbers are comparable only as
// far as the embedder that produced them matches.
type Baseline struct {
	Model     string                  `json:"model"`
	Dimension int                     `json:"dimension"`
	TopK      int                     `json:"top_k"`
	Runs      map[string]eval.Metrics `json:"runs"`
}

// fixtureSweeps are the deterministic runs the fixture is pinned on. Every one
// of them is free: keyword needs nothing but FTS5, vector and hybrid replay
// the frozen vectors, and the ceiling is an ordinary search on a written
// question. The planners that need a model are deliberately absent — they are
// not reproducible in CI, which is why they are not what CI pins.
func fixtureSweeps() map[string]EvalOptions {
	window, err := rewrite.New(rewrite.Options{Mode: rewrite.ModeWindow})
	if err != nil {
		panic("fixture sweeps: " + err.Error())
	}
	off, err := rewrite.New(rewrite.Options{Mode: rewrite.ModeOff})
	if err != nil {
		panic("fixture sweeps: " + err.Error())
	}
	return map[string]EvalOptions{
		"keyword-off":    {Mode: "keyword", Rewrite: rewrite.ModeOff, Planner: off},
		"keyword-window": {Mode: "keyword", Rewrite: rewrite.ModeWindow, Planner: window},
		"keyword-gold":   {Mode: "keyword", Rewrite: rewrite.ModeWindow, Planner: window, Gold: true},
		"vector-window":  {Mode: "vector", Rewrite: rewrite.ModeWindow, Planner: window},
		"hybrid-off":     {Mode: "hybrid", Rewrite: rewrite.ModeOff, Planner: off},
		"hybrid-window":  {Mode: "hybrid", Rewrite: rewrite.ModeWindow, Planner: window},
		"hybrid-gold":    {Mode: "hybrid", Rewrite: rewrite.ModeWindow, Planner: window, Gold: true},
	}
}

// sweepNames returns the sweeps in a stable order, so a failure reads the same
// way twice and a recorded baseline diffs cleanly.
func sweepNames() []string {
	names := make([]string, 0, len(fixtureSweeps()))
	for name := range fixtureSweeps() {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// scoreFixtureCorpus ingests the fixture corpus into an in-memory knowledge
// base against the frozen vectors and scores every sweep. It is the whole
// regression test in one function, and the recorder calls it too, so the
// numbers CI asserts are produced by the code CI runs.
func scoreFixtureCorpus(t *testing.T) (Baseline, map[string]eval.Report) {
	t.Helper()
	ctx := context.Background()

	fixture, err := eval.LoadFixture(filepath.Join(fixtureCorpusDir, "vectors.json"))
	if err != nil {
		t.Fatalf("load frozen vectors: %v", err)
	}
	embedder, err := fixture.Embedder(fixture.Model, fixture.Dimension)
	if err != nil {
		t.Fatalf("replay frozen vectors: %v", err)
	}

	db, err := storage.Open(":memory:")
	if err != nil {
		t.Fatalf("open memory DB: %v", err)
	}
	t.Cleanup(func() { _ = db.Close() })

	docs := storage.NewDocumentRepo(db.DB())
	ing := ingest.NewIngester(
		docs,
		storage.NewChunkRepo(db.DB()),
		storage.NewMetadataRepo(db.DB()),
		&ingest.DefaultFileExtractor{},
		// Chunking comes from the fixture, never from a constant held here:
		// chunk boundaries decide what the recorded keys are, so the two sides
		// cannot be allowed to hold separate opinions about them.
		&chunking.Chunker{Size: fixture.Chunking.Size, Overlap: fixture.Chunking.Overlap},
		embedder,
		t.TempDir(),
	)

	paths, err := filepath.Glob(filepath.Join(fixtureCorpusDir, "*.md"))
	if err != nil {
		t.Fatalf("glob corpus: %v", err)
	}
	sort.Strings(paths)
	for _, path := range paths {
		// A cache miss here is the fixture disagreeing with the corpus, and it
		// names the text it could not find rather than scoring it as nothing.
		if res := ing.IngestFile(ctx, path, ingest.Options{}); res.Err != nil {
			t.Fatalf("ingest %s: %v", filepath.Base(path), res.Err)
		}
	}

	set, err := eval.LoadSet(filepath.Join(fixtureCorpusDir, "labels.yaml"))
	if err != nil {
		t.Fatalf("load labels: %v", err)
	}

	topK := search.DefaultTopK
	baseline := Baseline{
		Model:     fixture.Model,
		Dimension: fixture.Dimension,
		TopK:      topK,
		Runs:      make(map[string]eval.Metrics),
	}
	reports := make(map[string]eval.Report)
	sweeps := fixtureSweeps()
	for _, name := range sweepNames() {
		opts := sweeps[name]
		opts.TopK = topK
		opts.Stage = eval.StageRetrieval
		opts.Embedding = fixture.Model

		ret := retrieval.New(modeSearcher{searcher: search.New(db.DB(), embedder), mode: opts.Mode})
		report, err := RunEval(ctx, set, ret.RetrieveMany, opts)
		if err != nil {
			t.Fatalf("sweep %s: %v", name, err)
		}
		baseline.Runs[name] = report.Overall
		reports[name] = report
	}
	return baseline, reports
}

// loadBaseline reads the recorded metrics.
func loadBaseline(t *testing.T) Baseline {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(fixtureCorpusDir, baselineFile))
	if err != nil {
		t.Fatalf("read baseline: %v\nrun `make eval-record-lsa` to record one", err)
	}
	var b Baseline
	if err := json.Unmarshal(data, &b); err != nil {
		t.Fatalf("parse baseline: %v", err)
	}
	return b
}

// TestFixtureCorpus_scoresItsRecordedBaseline is the test a ranking refactor
// fails. Chunking, the reduced search encoding, RRF fusion, the keyword leg's
// tokenizer and the query planners all feed these numbers; move any of them
// and the metrics move with them, on a laptop with no server running.
//
// A number that moved is not automatically a regression — it is a change that
// has to be looked at and then re-recorded on purpose with `make eval-record`.
func TestFixtureCorpus_scoresItsRecordedBaseline(t *testing.T) {
	want := loadBaseline(t)
	got, _ := scoreFixtureCorpus(t)

	if got.Model != want.Model || got.Dimension != want.Dimension {
		t.Fatalf("scored with %s/%d but the baseline was recorded with %s/%d — re-record",
			got.Model, got.Dimension, want.Model, want.Dimension)
	}
	if got.TopK != want.TopK {
		t.Fatalf("scored at top %d but the baseline is at top %d", got.TopK, want.TopK)
	}

	for _, name := range sweepNames() {
		w, ok := want.Runs[name]
		if !ok {
			t.Errorf("sweep %s has no recorded baseline — re-record", name)
			continue
		}
		assertMetrics(t, name, got.Runs[name], w)
	}
	for name := range want.Runs {
		if _, ok := got.Runs[name]; !ok {
			t.Errorf("baseline records sweep %s, which no longer runs", name)
		}
	}
}

// assertMetrics compares one sweep against its baseline. The tolerance is for
// float formatting through JSON, not for drift: the same corpus scored by the
// same code is the same number.
func assertMetrics(t *testing.T, sweep string, got, want eval.Metrics) {
	t.Helper()
	const tol = 1e-9

	for _, m := range []struct {
		name      string
		got, want float64
	}{
		{"hit", got.Hit, want.Hit},
		{"recall", got.Recall, want.Recall},
		{"precision", got.Precision, want.Precision},
		{"mrr", got.MRR, want.MRR},
		{"ndcg", got.NDCG, want.NDCG},
	} {
		if math.Abs(m.got-m.want) > tol {
			t.Errorf("%s %s = %.6f, baseline %.6f", sweep, m.name, m.got, m.want)
		}
	}
	for _, c := range []struct {
		name      string
		got, want int
	}{
		{"cases", got.Cases, want.Cases},
		{"labels", got.Labels, want.Labels},
		{"found", got.Found, want.Found},
	} {
		if c.got != c.want {
			t.Errorf("%s %s = %d, baseline %d", sweep, c.name, c.got, c.want)
		}
	}
}

// TestFixtureCorpus_goldCeilingBeatsTheWindow is the measurement #24 has been
// waiting for, and it costs no model call: the gold query is the standalone
// question a human would have typed, so the gap between it and the window fold
// is the room a rewrite has left to win. A window scoring at or above the
// ceiling would mean the ceiling is mislabelled, not that the window is
// perfect.
func TestFixtureCorpus_goldCeilingBeatsTheWindow(t *testing.T) {
	_, reports := scoreFixtureCorpus(t)

	for _, mode := range []string{"keyword", "hybrid"} {
		window := reports[mode+"-window"]
		gold := reports[mode+"-gold"]

		followups := followupCases(t)
		w := caseAverage(window, followups)
		g := caseAverage(gold, followups)
		t.Logf("%s follow-ups: window MRR %.4f, ceiling MRR %.4f, gap %+.4f", mode, w, g, g-w)

		if g < w {
			t.Errorf("%s ceiling (%.4f) scores below the window (%.4f) on the follow-ups: "+
				"a gold_query that retrieves worse than the raw follow-up is a mislabelled case",
				mode, g, w)
		}
	}
}

// followupCases are the ids carrying a gold query, which are the only ones the
// ceiling is defined for.
func followupCases(t *testing.T) map[string]bool {
	t.Helper()
	set, err := eval.LoadSet(filepath.Join(fixtureCorpusDir, "labels.yaml"))
	if err != nil {
		t.Fatalf("load labels: %v", err)
	}
	ids := make(map[string]bool)
	for _, c := range set.Cases {
		if c.GoldQuery != "" {
			ids[c.ID] = true
		}
	}
	if len(ids) == 0 {
		t.Fatal("the fixture label set carries no gold_query, so the ceiling is unmeasurable")
	}
	return ids
}

// caseAverage is the mean MRR over the named cases of one report.
func caseAverage(report eval.Report, ids map[string]bool) float64 {
	var sum float64
	var n int
	for _, row := range report.Cases {
		if ids[row.ID] {
			sum += row.Metrics.MRR
			n++
		}
	}
	if n == 0 {
		return 0
	}
	return sum / float64(n)
}
